from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def generate_launch_description():
    port_arg = DeclareLaunchArgument(
        'port',
        default_value='/dev/ttyUSB0',
        description='Linux serial device connected to the Arduino Nano D2 bridge.',
    )

    baud_rate_arg = DeclareLaunchArgument(
        'baud_rate',
        default_value='115200',
        description='Serial baud rate used by the Arduino sketch.',
    )

    publish_only_on_change_arg = DeclareLaunchArgument(
        'publish_only_on_change',
        default_value='false',
        description='Publish Nano D2 state only when the value changes.',
    )

    read_period_sec_arg = DeclareLaunchArgument(
        'read_period_sec',
        default_value='0.02',
        description='Serial polling period for the Nano D2 bridge.',
    )

    reconnect_period_sec_arg = DeclareLaunchArgument(
        'reconnect_period_sec',
        default_value='2.0',
        description='Seconds between serial reconnect attempts.',
    )

    input_topic_arg = DeclareLaunchArgument(
        'input_topic',
        default_value='/nano_d2_grounded',
        description='Bool topic produced by the Nano D2 serial bridge.',
    )

    text_topic_arg = DeclareLaunchArgument(
        'text_topic',
        default_value='/nano_d2_state',
        description='Text topic produced by the Nano D2 serial bridge.',
    )

    event_topic_arg = DeclareLaunchArgument(
        'event_topic',
        default_value='/nano_d2_event',
        description='Readable event topic generated by the monitor node.',
    )

    latch_grounded_event_arg = DeclareLaunchArgument(
        'latch_grounded_event',
        default_value='true',
        description='Latch grounded events until Nano D2 is released.',
    )

    periodic_status_sec_arg = DeclareLaunchArgument(
        'periodic_status_sec',
        default_value='2.0',
        description='Seconds between monitor status logs.',
    )

    serial_bridge_node = Node(
        package='dio13_serial_bridge',
        executable='nano_d2_serial_publisher',
        name='nano_d2_serial_publisher',
        output='screen',
        parameters=[{
            'port': LaunchConfiguration('port'),
            'baud_rate': LaunchConfiguration('baud_rate'),
            'read_period_sec': LaunchConfiguration('read_period_sec'),
            'topic_name': LaunchConfiguration('input_topic'),
            'text_topic_name': LaunchConfiguration('text_topic'),
            'publish_only_on_change': LaunchConfiguration('publish_only_on_change'),
            'reconnect_period_sec': LaunchConfiguration('reconnect_period_sec'),
        }],
    )

    monitor_node = Node(
        package='dio13_monitor_example',
        executable='nano_d2_monitor_node',
        name='nano_d2_monitor_node',
        output='screen',
        parameters=[{
            'input_topic': LaunchConfiguration('input_topic'),
            'event_topic': LaunchConfiguration('event_topic'),
            'latch_grounded_event': LaunchConfiguration('latch_grounded_event'),
            'periodic_status_sec': LaunchConfiguration('periodic_status_sec'),
        }],
    )

    return LaunchDescription([
        port_arg,
        baud_rate_arg,
        publish_only_on_change_arg,
        read_period_sec_arg,
        reconnect_period_sec_arg,
        input_topic_arg,
        text_topic_arg,
        event_topic_arg,
        latch_grounded_event_arg,
        periodic_status_sec_arg,
        serial_bridge_node,
        monitor_node,
    ])
