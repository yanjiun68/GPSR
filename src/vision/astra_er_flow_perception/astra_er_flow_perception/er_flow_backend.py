import json
import os
import re
import threading
from pathlib import Path

import numpy as np


class ERFlowBackend:
    """
    UnifoLM-ER-Flow image/prompt localization backend.

    The model is used for semantic localization/reacquisition. Metric depth is
    intentionally NOT generated by the VLM; depth is measured from Astra.
    """

    def __init__(
        self,
        model_path,
        processor_path="",
        device_map="auto",
        dtype="bfloat16",
        max_new_tokens=128,
        gpu_max_memory_gib=5,
        cpu_max_memory_gib=8,
        quantization_mode="nf4",
        use_double_quant=True,
        prompt_template="",
    ):
        self.model_path = os.path.expanduser(str(model_path))
        self.processor_path = os.path.expanduser(str(processor_path or model_path))
        self.device_map = device_map
        self.dtype_name = str(dtype)
        self.max_new_tokens = int(max_new_tokens)
        self.gpu_max_memory_gib = int(gpu_max_memory_gib)
        self.cpu_max_memory_gib = int(cpu_max_memory_gib)
        self.quantization_mode = str(quantization_mode).strip().lower()
        self.use_double_quant = bool(use_double_quant)
        # Section: Fail closed because this deployment must never load full-precision weights.
        if self.quantization_mode != "nf4":
            raise ValueError("ER-Flow requires quantization_mode='nf4'")
        self.prompt_template = prompt_template

        self.model = None
        self.processor = None
        self.torch = None
        self.quantization_verified = False
        self.quantized_linear_count = 0
        self._load_lock = threading.Lock()

    @property
    def loaded(self):
        return (
            self.model is not None
            and self.processor is not None
            and self.quantization_verified
        )

    def ensure_loaded(self):
        if self.loaded:
            return

        with self._load_lock:
            if self.loaded:
                return

            if not Path(self.model_path).exists():
                raise FileNotFoundError(
                    f"ER-Flow model path does not exist: {self.model_path}"
                )

            import torch
            from transformers import AutoProcessor, BitsAndBytesConfig

            try:
                from transformers import Qwen3VLForConditionalGeneration
                model_cls = Qwen3VLForConditionalGeneration
            except ImportError as exc:
                raise ImportError(
                    "Qwen3VLForConditionalGeneration is unavailable. "
                    "Upgrade Transformers to a version that supports Qwen3-VL."
                ) from exc

            dtype_map = {
                "float32": torch.float32,
                "float16": torch.float16,
                "bfloat16": torch.bfloat16,
                "auto": "auto",
            }
            torch_dtype = dtype_map.get(self.dtype_name.lower(), "auto")
            # Section: Configure mandatory NF4 weights with BF16 math and nested quantization.
            quantization_config = BitsAndBytesConfig(
                load_in_4bit=True,
                bnb_4bit_quant_type="nf4",
                bnb_4bit_compute_dtype=torch_dtype,
                bnb_4bit_use_double_quant=self.use_double_quant,
            )

            self.processor = AutoProcessor.from_pretrained(
                self.processor_path,
                trust_remote_code=True,
            )

            kwargs = {
                "device_map": self.device_map,
                "low_cpu_mem_usage": True,
                "quantization_config": quantization_config,
                "trust_remote_code": True,
            }
            # Section: Reserve GPU headroom for vision activations on the 8 GiB RTX 4060.
            if self.device_map == "auto" and torch.cuda.is_available():
                kwargs["max_memory"] = {
                    0: f"{self.gpu_max_memory_gib}GiB",
                    "cpu": f"{self.cpu_max_memory_gib}GiB",
                }

            # Transformers versions differ between torch_dtype= and dtype=.
            try:
                try:
                    self.model = model_cls.from_pretrained(
                        self.model_path,
                        dtype=torch_dtype,
                        **kwargs,
                    )
                except TypeError:
                    self.model = model_cls.from_pretrained(
                        self.model_path,
                        torch_dtype=torch_dtype,
                        **kwargs,
                    )
            except Exception:
                # Section: Release cached allocations before a later inference retry.
                self.model = None
                self.quantization_verified = False
                self.quantized_linear_count = 0
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()
                raise

            # Section: Verify conversion happened instead of trusting configuration acceptance.
            self.quantized_linear_count = sum(
                1
                for module in self.model.modules()
                if module.__class__.__name__ == "Linear4bit"
                and module.__class__.__module__.startswith("bitsandbytes")
            )
            if self.quantized_linear_count <= 0:
                self.model = None
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()
                raise RuntimeError(
                    "NF4 verification failed: no BitsAndBytes Linear4bit layers found"
                )
            self.quantization_verified = True
            self.model.eval()
            self.torch = torch

    def build_prompt(self, target, user_prompt=""):
        """Special function: Substitute command fields without interpreting JSON braces."""
        # Section: Literal replacement preserves JSON examples embedded in the prompt template.
        return (
            self.prompt_template
            .replace("{target}", str(target))
            .replace("{user_prompt}", str(user_prompt).strip())
        )

    def infer_roi(self, bgr_image, target, user_prompt=""):
        self.ensure_loaded()

        from PIL import Image

        rgb = bgr_image[..., ::-1]
        pil_image = Image.fromarray(np.ascontiguousarray(rgb))

        prompt = self.build_prompt(target, user_prompt)

        messages = [
            {
                "role": "user",
                "content": [
                    {"type": "image", "image": pil_image},
                    {"type": "text", "text": prompt},
                ],
            }
        ]

        inputs = self.processor.apply_chat_template(
            messages,
            tokenize=True,
            add_generation_prompt=True,
            return_dict=True,
            return_tensors="pt",
        )

        # device_map="auto" may shard the model. For the common single-GPU case,
        # sending processor tensors to the first model device is sufficient.
        try:
            device = next(self.model.parameters()).device
            inputs = {
                key: value.to(device) if hasattr(value, "to") else value
                for key, value in inputs.items()
            }
        except Exception:
            pass

        with self.torch.inference_mode():
            generated = self.model.generate(
                **inputs,
                max_new_tokens=self.max_new_tokens,
                do_sample=False,
            )

        input_ids = inputs.get("input_ids")
        if input_ids is not None:
            generated = generated[:, input_ids.shape[1]:]

        text = self.processor.batch_decode(
            generated,
            skip_special_tokens=True,
            clean_up_tokenization_spaces=False,
        )[0].strip()

        result = self._parse_localization(text, bgr_image.shape[1], bgr_image.shape[0])
        result["raw_model_output"] = text
        return result

    @staticmethod
    def _extract_json(text):
        start = text.find("{")
        end = text.rfind("}")
        if start >= 0 and end > start:
            try:
                return json.loads(text[start:end + 1])
            except json.JSONDecodeError:
                return None
        return None

    @classmethod
    def _parse_localization(cls, text, width, height):
        obj = cls._extract_json(text)

        if isinstance(obj, dict):
            found = bool(obj.get("found", True))
            bbox = obj.get("bbox") or obj.get("box") or obj.get("roi")
            confidence = obj.get("confidence", obj.get("score", 1.0))
            if found and isinstance(bbox, (list, tuple)) and len(bbox) >= 4:
                return cls._normalize_bbox(bbox[:4], confidence, width, height)
            if not found:
                return {
                    "found": False,
                    "bbox_xyxy": None,
                    "roi_xywh": None,
                    "confidence": float(confidence or 0.0),
                }

        # Fallback for outputs like <box>(x1,y1),(x2,y2)</box>
        nums = re.findall(r"-?\d+(?:\.\d+)?", text)
        if len(nums) >= 4:
            vals = [float(v) for v in nums[:4]]
            return cls._normalize_bbox(vals, 1.0, width, height)

        return {
            "found": False,
            "bbox_xyxy": None,
            "roi_xywh": None,
            "confidence": 0.0,
        }

    @staticmethod
    def _normalize_bbox(bbox, confidence, width, height):
        x1, y1, x2, y2 = [float(v) for v in bbox]

        # If the model returns the common 0..1000 normalized grounding scale
        # and values exceed this image's pixel dimensions, convert to pixels.
        if max(x1, x2) > width and max(x1, x2) <= 1000:
            x1 = x1 / 1000.0 * width
            x2 = x2 / 1000.0 * width
        if max(y1, y2) > height and max(y1, y2) <= 1000:
            y1 = y1 / 1000.0 * height
            y2 = y2 / 1000.0 * height

        x1 = max(0, min(int(round(x1)), width - 1))
        y1 = max(0, min(int(round(y1)), height - 1))
        x2 = max(x1 + 1, min(int(round(x2)), width))
        y2 = max(y1 + 1, min(int(round(y2)), height))

        return {
            "found": True,
            "bbox_xyxy": [x1, y1, x2, y2],
            "roi_xywh": [x1, y1, x2 - x1, y2 - y1],
            "confidence": float(confidence),
        }
